export type UILanguage='en'|'es'|'ru'|'de';
export function translate(message:string,language:UILanguage,values:Record<string,unknown>={}):string{
 const key=message.trim().replace(/\s+/g,' '),catalog=language==='es'?spanish:language==='de'?german:language==='ru'?russian:undefined;
 let text=message;
 if(catalog){
  const entry=catalog[key];
  if(entry){
   const plural=new Intl.PluralRules(language).select(Number(values.v0));
   const index=plural==='one'?0:language==='ru'&&plural==='few'?1:language==='ru'?2:1;
   const translated=Array.isArray(entry)?entry[Math.min(index,entry.length-1)]:entry;
   text=(message.startsWith(' ')?' ':'')+translated+(message.endsWith(' ')?' ':'');
  }else if(/^Sending part \d+\/\d+$/.test(key)){
   const match=key.match(/(\d+)\/(\d+)/)!;return translate('Sending part {v0}/{v1}',language,{v0:match[1],v1:match[2]});
  }else if(message.startsWith('Connection lost. '))return translate('Connection lost.',language)+' '+translate(message.slice(17),language);
 }
 return text.replace(/\{(\w+)\}/g,(token,key)=>key in values?String(values[key]):token);
}
